// 阅读态的标签渲染（#14 定稿 → #29 落地）。
//
// 两件事住这里，其余（插到渲染管线的哪一步、插几次）住在 main.js：
//   1. **识别规则**：照 Obsidian 官方语法——`#` 开头，后面跟字母 / 数字 / `_` / `-` / `/`
//      及通用 Unicode（中文合法），**须至少含一个非数字字符**（`#1984` 不是标签）；
//      嵌套 `#a/b` 合法，显示完整层级。
//   2. **画一个标签**（`tagChipHtml`）：**全应用唯一一份**。#12 的「声明区显示」
//      将来要把 YAML 的 `tags` 字段画成标签，也走它，不许另写一份。
//
// 挂的是**行内规则**（和双链 `#7`、图片 `#8` 同一处），不是自己扫原文。这一层天然把
// 五类地方挡在外面，不必特判、也不会误伤：
//   - **代码块** → 块级解析就吞成 code/fence token 了，行内规则根本见不到；
//   - **行内代码** → 反引号规则先于本规则把整段消费掉，`#RRGGBB` 因此安全；
//   - **链接目标与锚点** `[文字](url#锚点)` → link 规则整体吃掉，`#锚点` 到不了这里；
//   - **URL 里的 `#`** → `https://x/#a` 的 `#` 前面是 `/`、`x#a` 前面是 `x`，过不了
//     「前面必须是空白或行首」这一关（linkify 是行内解析之后的另一趟，那时已经晚了，
//     所以这道门是必要的，不是保险）；
//   - **转义 `\#`** → escape 规则先消费，这里见到的只是普通字符。
//
// **「前面必须是空白或行首」是 Obsidian 的硬规矩**（多方资料一致：`#` 前必须有个空格，
// `bug#urgent` 不是标签，只有行首或空白后的 `#` 才算），也是上面那道门。
// 一条要留意的推论：**中文标点紧贴的 `#` 不算标签**——`标签：#工作`、`，#标签` 都不渲染，
// 必须写成 `标签： #工作`。这是与 Obsidian 一致的取舍，不是漏了。全库只读实测（854 篇，
// **用本模块本身在真实渲染器上整体跑一遍再数**）：
//   - 渲染后共 555 颗胶囊，只有 12 个不同的名字（#工作 239、#AI 117、#需求 105…），
//     没有一颗落在链接文字里、没有一颗是 URL 或标题记号变的；
//   - `#` 紧贴非空白字符的只有 36 处，逐条看过**没有一处是真标签**——全是 URL 锚点、
//     目录跳转 `(#1-设计目的)`、行内代码里的 `\`#RRGGBB\``、转义的颜色值 `\#3B82F6`；
//   - 另有 20 处是 `Problem #1` `#2` 这种纯数字（英文读书笔记里的编号），按下面
//     「至少一个非数字字符」的规则正确地留作普通文字；
//   - 唯一被这条边界挡掉的「可能本该是标签」的写法只有 1 处：散文里手写的
//     `（#数字后只允许空格规则）`。
// 所以这条边界在本库几乎零代价，却挡住了全部裸 URL 锚点。
//
// 一条**已知的简化**（不是疏漏）：`[看 #标签 这页](url)` 的链接文字里那颗标签仍会被画成
// 胶囊。要挡掉它得在行内规则之外再走一趟 token 树，而全库实测这类写法 **0 处**，
// 为它加一趟扫描不划算。真机上若撞见再补。
//
// 顺带一条**不特判**：`#ffffff` 这种十六进制颜色按上面这套语法恰好是合法标签，就照标签
// 渲染，与 Obsidian 一致（实际写颜色的地方基本都在代码块里，早就被挡在外面了）。
//
// 识别规则与「画标签」都是纯逻辑，所以能进 `node --test`；渲染断言同样用真实渲染器
// 整体跑一遍再断言，不另写复刻逻辑的复算脚本。

/**
 * 标签名到此为止的字符——**写成「不在这张表里就继续吃」**。
 *
 * 表里是空白与各种会截断标签的标点（中英文都列上）。三种字符**不在**表里，因为它们是
 * 合法标签字符：`-`（`kebab-case`）、`_`（`snake_case`）、`/`（嵌套层级）；emoji 之类的
 * 通用 Unicode 同样不在表里（官方允许）。`#` 在表里——官方字符表里没有它，`##标题`
 * 于是只截得出一段空名字，整处不成标签。
 *
 * 破折号 `—` 与省略号 `…` 在表里，但 `-` 不在；这两个字形像，别混。
 */
const NOT_IN_TAG = /[\s#~`!@$%^&*+=\\|;:'",.<>?()[\]{}—…、。，；：！？（）【】《》“”‘’]/u;

/** 至少含一个非数字字符——`#1984` 不是标签。 */
const hasNonDigit = (name) => /[^\d]/.test(name);

/** 从 `at` 起吃掉一个标签名（不含 `#`）。 */
function readTagName(src, at) {
  let i = at;
  while (i < src.length && !NOT_IN_TAG.test(src[i])) i++;
  return src.slice(at, i);
}

/**
 * 画一个标签：全应用唯一一份，正文里的 `#标签` 与将来 YAML `tags` 字段都走这里。
 *
 * **不自作主张加 `#`**：正文规则自己把 `#` 拼进来（Obsidian 阅读态显示带 `#`），
 * YAML 里是裸名字（全库 202 个标签值 0 个带 `#`），显示成什么样由那边的定稿说了算。
 * 这里只管「把给到的文字画成一颗小胶囊」——连同转义一起，别处不必也不该再写一遍。
 */
export function tagChipHtml(text) {
  return '<span class="tag-chip">' + escapeHtml(String(text)) + '</span>';
}

/** 只转义这五个字符，和 markdown-it 的口径一致；单独写一份是为了让别处（YAML 显示）不必先有一个渲染器实例。 */
function escapeHtml(s) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

/**
 * 安装渲染钩子：行内遇到 `#标签` 就换成一颗胶囊。
 *
 * 插在 `link` 之前：`link` 一旦命中就整体吃掉了，插在它后面等于放跑 `[文字](url#锚点)`。
 * 失败一律返回 `false`——让原文原样留在文字里，宁可不翻也不翻错。
 */
export function installTagRule(md) {
  md.inline.ruler.before('link', 'obsidian_tag', (state, silent) => {
    const pos = state.pos;
    if (state.src.charCodeAt(pos) !== 0x23 /* # */) return false;
    // 行首，或前面是空白——Obsidian 的边界，也是 URL 锚点进不来的那道门
    if (pos > 0 && !/\s/.test(state.src[pos - 1])) return false;

    const name = readTagName(state.src, pos + 1);
    if (!name || !hasNonDigit(name)) return false;

    if (!silent) {
      const token = state.push('tag', '', 0);
      token.content = name;
    }
    state.pos = pos + 1 + name.length;
    return true;
  });

  // 正文里的标签要带 `#`（Obsidian 阅读态就是这么显示的），所以在这里拼上
  md.renderer.rules.tag = (tokens, idx) => tagChipHtml('#' + tokens[idx].content);
}
